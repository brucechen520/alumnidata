const assert = require('assert');
const fs = require('fs');
const babel = require('@babel/core');
const original = require.extensions['.js'];
require.extensions['.js'] = (module, filename) => {
  if (!filename.includes('/src/')) return original(module, filename);
  const source = fs.readFileSync(filename, 'utf8');
  module._compile(babel.transformSync(source, { plugins: ['@babel/plugin-transform-modules-commonjs'] }).code, filename);
};
const { http } = require('../src/shared/http');
const api = require('../src/industry/api');
const { api2 } = require('../src/assets/api');
let location = { href: '' };
let alerts = [];
global.window = { location, alert: message => alerts.push(message) };
let calls = [];
let status = 200;
http.defaults.adapter = config => {
  calls.push(config);
  if (status !== 200) return Promise.reject({ response: { status, data: { message: '後端訊息' } } });
  return Promise.resolve({ data: { code: 'success' }, status: 200, config });
};
async function run() {
  let resolveIdentity;
  const identity = new Promise(resolve => { resolveIdentity = resolve; });
  let path = '/JobQuery';
  api.setRequestContext(identity, () => path);
  status = 401;
  const pending = api.request('post', '/ee/api/api_project_get.php', {}).catch(() => {});
  await new Promise(resolve => setImmediate(resolve));
  assert.strictEqual(location.href, '');
  path = '/manage';
  resolveIdentity({ name: '訪客' });
  await pending;
  assert.strictEqual(location.href, '');
  api.setRequestContext(Promise.resolve({ name: '會員', id: 1 }), () => '/JobQuery');
  await api.request('post', 'api_vacancy_get.php', {}).catch(() => {});
  assert.strictEqual(location.href, '/ee/index.php');
  location.href = '';
  api.setRequestContext(Promise.resolve({ name: '訪客' }), () => '/WebsiteFilling');
  await api.getData('/ee/api/api_web.php', { params: { methods: 'insert' } }).catch(() => {});
  assert.strictEqual(location.href, '/ee/index.php');
  location.href = '';
  api.setRequestContext(Promise.resolve('failed'), () => '/products');
  await api.request('post', 'api_product_get.php', {}).catch(() => {});
  assert.strictEqual(location.href, '/ee/index.php');
  status = 403;
  await api.getData('api_web.php').catch(() => {});
  assert.deepStrictEqual(alerts, ['後端訊息']);
  status = 200;
  calls = [];
  assert.deepStrictEqual(await api.getData('/ee/api/api_permit.php', { params: { methods: 'select' } }), { code: 'success' });
  assert.strictEqual(calls[0].url, '/ee/api/api_permit.php');
  assert.strictEqual(calls[0].params.methods, 'select');
  const form = new FormData(); form.append('photo', 'x');
  await api.request('post', '/ee/api/api_photo_update.php', form);
  await api.request('post', 'api_product_get.php', { key: 'value' });
  assert.strictEqual(calls[1].data, form);
  assert.ok(!String(calls[1].headers['Content-Type']).includes('multipart'));
  assert.strictEqual(calls[2].headers['Content-Type'], 'application/json;charset=utf-8');
  assert.strictEqual(calls[2].data, '{"key":"value"}');
  let success = false, complete = false, failure = false;
  await api2.product_get({}, data => { success = data.code === 'success'; }, () => { complete = true; });
  assert.ok(success && complete);
  status = 500; complete = false;
  await api2.product_get({}, null, () => { complete = true; }, () => { failure = true; });
  assert.ok(failure && complete);
  status = 200;
  await api.logout();
  assert.strictEqual(calls[calls.length - 1].url, '/ee/api/api_auth_logout.php');
  assert.strictEqual(location.href, '/ee/index.php');
  status = 500;
  await api.logout();
  assert.strictEqual(location.href, '/ee/logout.php');
  console.log('industry API checks passed');
}
run().catch(error => { console.error(error); process.exitCode = 1; });
